// 사용자 언어 설정 및 브라우저 로캘 기반 활성 언어 산출 목적
export function resolveLanguage(languageSetting, navigatorLanguage = 'en') {
  if (languageSetting === 'ko' || languageSetting === 'en') {
    return languageSetting;
  }
  const safeNavigatorLanguage = String(navigatorLanguage || '').toLowerCase();
  return safeNavigatorLanguage.startsWith('ko') ? 'ko' : 'en';
}
